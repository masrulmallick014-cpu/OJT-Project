export function getRandomQuote() {
    const index = Math.floor(Math.random() * MOTIVATIONAL_QUOTES.length);
    return MOTIVATIONAL_QUOTES[index];
}
export function getRandomQuoteByCategory(category, excludeId) {
    const pool = category === 'All'
        ? MOTIVATIONAL_QUOTES
        : MOTIVATIONAL_QUOTES.filter((q) => q.category === category);
    const filtered = pool.length > 1 && excludeId ? pool.filter((q) => q.id !== excludeId) : pool;
    const source = filtered.length > 0 ? filtered : MOTIVATIONAL_QUOTES;
    const index = Math.floor(Math.random() * source.length);
    return source[index];
}
export function getQuoteForDay(dayOfYear) {
    const day = dayOfYear ?? Math.floor((Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / 1000 / 60 / 60 / 24);
    const index = Math.abs(day) % MOTIVATIONAL_QUOTES.length;
    return MOTIVATIONAL_QUOTES[index];
}
